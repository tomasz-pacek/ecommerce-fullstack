"use server";

import { db } from "@/db";
import { laptops } from "@/db/schema";
import { getCurrentSession } from "@/lib/auth-utils";
import { laptopFormSchema } from "@/lib/validations/laptop-form-schema";

import { eq, sql } from "drizzle-orm";
import { revalidatePath, updateTag } from "next/cache";
import * as z from "zod";

export const createLaptop = async (data: z.infer<typeof laptopFormSchema>) => {
  const session = await getCurrentSession();
  if (!session || session.user.role !== "admin") {
    return { success: false, error: "Forbidden" };
  }

  const parsedData = laptopFormSchema.safeParse(data);
  if (!parsedData.success) return { success: false, error: "Invalid data" };

  try {
    const slug = z.string().slugify().parse(parsedData.data.title);
    await db.insert(laptops).values({ ...parsedData.data, slug }); //SKU is automatically generated by database
    revalidatePath("/admin/catalog");
    return { success: true };
  } catch (error) {
    console.error(error);
    return {
      success: false,
      error: "Something went wrong while creating laptop",
    };
  }
};

export const updateLaptop = async (
  data: z.infer<typeof laptopFormSchema>,
  laptopId: string,
  slug: string,
) => {
  const session = await getCurrentSession();
  if (!session || session.user.role !== "admin") {
    return { success: false, error: "Forbidden" };
  }
  const parsedData = laptopFormSchema.safeParse(data);
  if (!parsedData.success) return { success: false, error: "Invalid data" };

  try {
    await db
      .update(laptops)
      .set({ ...parsedData.data, updatedAt: sql`now()` })
      .where(eq(laptops.id, laptopId));
    updateTag(`product-${slug}`); //make the cache outdated
    revalidatePath("/admin/catalog");
    return { success: true };
  } catch (error) {
    console.error(error);
    return {
      success: false,
      error: "Something went wrong while updating laptop",
    };
  }
};

export const deleteLaptop = async (laptopId: string) => {
  const session = await getCurrentSession();
  if (!session || session.user.role !== "admin") {
    return { success: false, error: "Forbidden" };
  }

  try {
    await db.delete(laptops).where(eq(laptops.id, laptopId));
    revalidatePath("/admin/catalog");
    return { success: true };
  } catch (error) {
    console.error(error);
    return {
      success: false,
      error: "Something went wrong while deleting laptop",
    };
  }
};
